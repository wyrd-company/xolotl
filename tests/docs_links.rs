//! Every link in the docs must reach something its reader can open.
//!
//! wyrd.foo publishes the pages in docs/user that docs.yml puts in its nav and
//! the assets that docs.yml lists. Nothing else in the repository is on the
//! site, so a page links only to those, to a heading, or to a full URL. A page
//! links to another page as `page.md` or `page.md#heading`, the form that also
//! works on GitHub.
//!
//! The README is read on GitHub: its relative links must reach files in the
//! repository. Links to the published docs on wyrd.foo must name a published
//! page and heading.

use std::collections::{BTreeMap, BTreeSet};
use std::path::{Path, PathBuf};

use pulldown_cmark::{BrokenLink, CowStr, Event, LinkType, Options, Parser, Tag, TagEnd};

const ROOT: &str = env!("CARGO_MANIFEST_DIR");
const DOCS: &str = "docs/user";
const SITE_DOCS: &str = "https://wyrd.foo/docs/xolotl/";
const REPO: &str = "https://github.com/wyrd-company/xolotl/";
/// Files in the repository that a published page may link to on GitHub: a
/// reader of the site needs them and they are not on the site.
const REPO_FILES_FOR_READERS: &[&str] = &["config.example.toml", "LICENSE"];
/// Generated by intentional; their links come from intents, not from pages.
const CHANGELOG: &str = "CHANGELOG.md";

struct Link {
    line: usize,
    target: String,
}

struct Document {
    links: Vec<Link>,
    /// Heading anchors, as wyrd.foo and GitHub make them.
    anchors: BTreeSet<String>,
    /// `[text][label]` with no definition for `label`.
    broken_references: Vec<Link>,
}

struct Site {
    /// Published pages by slug.
    pages: BTreeMap<String, Document>,
    /// Published assets, relative to docs/user.
    assets: BTreeSet<String>,
}

#[test]
fn published_pages_link_only_to_published_content() {
    let site = site();
    let mut problems = Vec::new();
    for (slug, page) in &site.pages {
        let file = format!("{DOCS}/{slug}.md");
        report_broken_references(&file, page, &mut problems);
        for link in &page.links {
            if let Some(problem) = page_link_problem(&site, slug, &link.target) {
                problems.push(format!("{file}:{}: {}: {problem}", link.line, link.target));
            }
        }
    }
    assert_no_problems(problems);
}

#[test]
fn every_page_in_docs_user_is_published() {
    let nav = nav_pages();
    let mut problems = Vec::new();
    for path in files_in(Path::new(ROOT).join(DOCS).as_path()) {
        let name = path.file_name().unwrap().to_str().unwrap();
        let Some(slug) = name.strip_suffix(".md") else { continue };
        if name == CHANGELOG {
            continue;
        }
        let source = std::fs::read_to_string(&path).unwrap();
        if !front_matter(&source).lines().any(|l| l.trim() == "product: xolotl") {
            problems.push(format!("{DOCS}/{name}: front matter has no `product: xolotl`, so wyrd.foo does not publish it"));
        }
        if !nav.contains(slug) {
            problems.push(format!("{DOCS}/{name}: docs.yml nav does not list {slug}, so the page has no place on wyrd.foo"));
        }
    }
    for slug in &nav {
        if !Path::new(ROOT).join(DOCS).join(format!("{slug}.md")).is_file() {
            problems.push(format!("{DOCS}/docs.yml: nav lists {slug}, but {DOCS}/{slug}.md does not exist"));
        }
    }
    assert_no_problems(problems);
}

#[test]
fn readme_links_reach_files_and_published_pages() {
    let site = site();
    let source = std::fs::read_to_string(Path::new(ROOT).join("README.md")).unwrap();
    let readme = parse(&source);
    let mut problems = Vec::new();
    report_broken_references("README.md", &readme, &mut problems);
    for link in &readme.links {
        if let Some(problem) = repo_link_problem(&site, &readme, &link.target) {
            problems.push(format!("README.md:{}: {}: {problem}", link.line, link.target));
        }
    }
    assert_no_problems(problems);
}

#[test]
fn anchors_follow_the_heading_text() {
    let doc = parse("# Point the CLI at the server\n## `xolotl keys` and `--json`\n## Rate limits\n## Rate limits\n");
    let anchors: Vec<_> = doc.anchors.into_iter().collect();
    assert_eq!(anchors, ["point-the-cli-at-the-server", "rate-limits", "rate-limits-1", "xolotl-keys-and---json"]);
}

#[test]
fn page_links_are_checked_against_the_published_set() {
    let mut pages = BTreeMap::new();
    pages.insert("one".to_string(), parse("# One\n## Run it\n"));
    pages.insert("two".to_string(), parse("# Two\n"));
    let site = Site { pages, assets: BTreeSet::from(["assets/shot.png".to_string()]) };
    let ok = [
        "two.md",
        "two.md#two",
        "#run-it",
        "assets/shot.png",
        "https://example.com/x",
        "https://wyrd.foo/docs/xolotl/two#two",
        "https://wyrd.foo/docs/xolotl/",
    ];
    for target in ok {
        assert_eq!(page_link_problem(&site, "one", target), None, "{target}");
    }
    let refused = [
        "two",
        "two.md#missing",
        "#missing",
        "three.md",
        "../design/README.md",
        "/docs/xolotl/two",
        "assets/other.png",
        "https://github.com/wyrd-company/xolotl/blob/main/docs/design/x.md",
        "https://wyrd.foo/docs/xolotl/three",
    ];
    for target in refused {
        assert!(page_link_problem(&site, "one", target).is_some(), "{target} must be refused");
    }
}

// --- rules -----------------------------------------------------------------

/// Why a link on the published page `slug` does not reach published content.
fn page_link_problem(site: &Site, slug: &str, target: &str) -> Option<String> {
    let page = &site.pages[slug];
    if let Some(anchor) = target.strip_prefix('#') {
        return anchor_problem(page, anchor, "this page");
    }
    if is_url(target) {
        return url_problem(site, target);
    }
    if target.starts_with('/') {
        return Some("use a relative link, such as `page.md`; a root path does not resolve on GitHub".into());
    }
    let (path, anchor) = split_anchor(target);
    let path = percent_decode(path);
    let Some(resolved) = normalize(&Path::new(DOCS).join(&path)) else {
        return Some("leaves the repository".into());
    };
    let Ok(within) = resolved.strip_prefix(DOCS) else {
        return Some(format!("{} is not published on wyrd.foo; link to a page in {DOCS} or to a full URL", resolved.display()));
    };
    let within = within.to_str().unwrap().to_string();
    if let Some(other) = within.strip_suffix(".md") {
        return match site.pages.get(other) {
            Some(doc) => anchor.and_then(|a| anchor_problem(doc, a, &within)),
            None => Some(format!("{DOCS}/{within} is not a published page")),
        };
    }
    if site.assets.contains(&within) {
        return anchor.map(|_| "an asset has no headings".into());
    }
    if site.pages.contains_key(&within) {
        return Some(format!("write `{within}.md`, so the link works on GitHub too"));
    }
    if Path::new(ROOT).join(DOCS).join(&within).exists() {
        return Some(format!("{DOCS}/{within} is not in the assets list of docs.yml, so it is not published"));
    }
    Some(format!("{DOCS}/{within} does not exist"))
}

/// Why a relative link in a file read on GitHub does not reach a file.
fn repo_link_problem(site: &Site, doc: &Document, target: &str) -> Option<String> {
    if let Some(anchor) = target.strip_prefix('#') {
        return anchor_problem(doc, anchor, "this file");
    }
    if is_url(target) {
        return url_problem(site, target);
    }
    if target.starts_with('/') {
        return Some("use a path relative to this file".into());
    }
    let (path, anchor) = split_anchor(target);
    let Some(resolved) = normalize(Path::new(&percent_decode(path))) else {
        return Some("leaves the repository".into());
    };
    let full = Path::new(ROOT).join(&resolved);
    if !full.exists() {
        return Some(format!("{} does not exist", resolved.display()));
    }
    match anchor {
        Some(anchor) if full.extension().is_some_and(|e| e == "md") => {
            let other = parse(&std::fs::read_to_string(&full).unwrap());
            anchor_problem(&other, anchor, &resolved.display().to_string())
        }
        Some(_) => Some("only a Markdown file has headings to link to".into()),
        None => None,
    }
}

/// Rules for full URLs: links into the published docs must name a page and
/// heading that exist, and links into this repository on GitHub must name a
/// file a reader needs.
fn url_problem(site: &Site, target: &str) -> Option<String> {
    if let Some(rest) = target.strip_prefix(SITE_DOCS) {
        let (slug, anchor) = split_anchor(rest);
        let slug = slug.trim_end_matches('/');
        if slug.is_empty() {
            return None;
        }
        return match site.pages.get(slug) {
            Some(doc) => anchor.and_then(|a| anchor_problem(doc, a, &format!("{slug}.md"))),
            None => Some(format!("{slug} is not a published page")),
        };
    }
    let rest = target.strip_prefix(REPO)?;
    let path = rest.strip_prefix("blob/").or_else(|| rest.strip_prefix("tree/"))?;
    let (_, path) = path.split_once('/').unwrap_or((path, ""));
    let path = path.split(['#', '?']).next().unwrap();
    if REPO_FILES_FOR_READERS.contains(&path) {
        return None;
    }
    Some(format!(
        "{path} is a repository file, not user documentation; link to a published page, or add the file to REPO_FILES_FOR_READERS"
    ))
}

fn anchor_problem(doc: &Document, anchor: &str, place: &str) -> Option<String> {
    let anchor = percent_decode(anchor);
    if doc.anchors.contains(&anchor) { None } else { Some(format!("{place} has no heading with the anchor #{anchor}")) }
}

fn report_broken_references(file: &str, doc: &Document, problems: &mut Vec<String>) {
    for link in &doc.broken_references {
        problems.push(format!("{file}:{}: [{}]: the reference has no definition", link.line, link.target));
    }
}

fn assert_no_problems(problems: Vec<String>) {
    assert!(problems.is_empty(), "{} broken or unpublished links:\n{}", problems.len(), problems.join("\n"));
}

// --- the published set -------------------------------------------------------

fn site() -> Site {
    let pages = nav_pages()
        .into_iter()
        .filter_map(|slug| {
            let source = std::fs::read_to_string(Path::new(ROOT).join(DOCS).join(format!("{slug}.md"))).ok()?;
            Some((slug, parse(&source)))
        })
        .collect();
    Site { pages, assets: docs_yml_assets() }
}

fn docs_yml() -> String {
    std::fs::read_to_string(Path::new(ROOT).join(DOCS).join("docs.yml")).unwrap()
}

/// The top-level `assets:` list of docs.yml.
fn docs_yml_assets() -> BTreeSet<String> {
    let docs = docs_yml();
    let assets: BTreeSet<String> =
        docs.lines().skip_while(|l| *l != "assets:").skip(1).map_while(|l| l.strip_prefix("  - ")).map(|a| a.trim().to_string()).collect();
    assert!(!assets.is_empty(), "docs.yml has no top-level assets list");
    assets
}

/// Every slug in the `pages: [...]` lists of the docs.yml nav.
fn nav_pages() -> BTreeSet<String> {
    let docs = docs_yml();
    let pages: BTreeSet<String> = docs
        .lines()
        .filter_map(|l| l.trim().strip_prefix("pages: ["))
        .flat_map(|l| l.trim_end_matches(']').split(',').map(|s| s.trim().to_string()).collect::<Vec<_>>())
        .filter(|s| !s.is_empty())
        .collect();
    assert!(!pages.is_empty(), "docs.yml has no nav pages");
    pages
}

fn files_in(dir: &Path) -> Vec<PathBuf> {
    let mut files: Vec<_> = std::fs::read_dir(dir).unwrap().map(|e| e.unwrap().path()).filter(|p| p.is_file()).collect();
    files.sort();
    files
}

// --- Markdown -----------------------------------------------------------------

fn front_matter(source: &str) -> &str {
    source.strip_prefix("---\n").and_then(|rest| rest.split_once("\n---").map(|(front, _)| front)).unwrap_or("")
}

fn parse(source: &str) -> Document {
    let line_of = |offset: usize| source[..offset].matches('\n').count() + 1;
    let broken = std::cell::RefCell::new(Vec::new());
    let mut callback = |link: BrokenLink<'_>| {
        if matches!(link.link_type, LinkType::ReferenceUnknown | LinkType::CollapsedUnknown) {
            broken.borrow_mut().push(Link { line: line_of(link.span.start), target: link.reference.to_string() });
        }
        None::<(CowStr<'_>, CowStr<'_>)>
    };
    let options = Options::ENABLE_TABLES | Options::ENABLE_YAML_STYLE_METADATA_BLOCKS | Options::ENABLE_STRIKETHROUGH;
    let parser = Parser::new_with_broken_link_callback(source, options, Some(&mut callback));

    let mut links = Vec::new();
    let mut anchors = BTreeSet::new();
    let mut heading: Option<String> = None;
    for (event, range) in parser.into_offset_iter() {
        let line = line_of(range.start);
        match event {
            Event::Start(Tag::Link { dest_url, .. } | Tag::Image { dest_url, .. }) => {
                links.push(Link { line, target: dest_url.to_string() });
            }
            Event::Html(html) | Event::InlineHtml(html) => {
                links.extend(html_targets(&html).into_iter().map(|target| Link { line, target }));
            }
            Event::Start(Tag::Heading { .. }) => heading = Some(String::new()),
            Event::Text(text) | Event::Code(text) => {
                if let Some(h) = heading.as_mut() {
                    h.push_str(&text);
                }
            }
            Event::End(TagEnd::Heading(_)) => {
                let base = slug(&heading.take().unwrap_or_default());
                let mut anchor = base.clone();
                let mut n = 0;
                while anchors.contains(&anchor) {
                    n += 1;
                    anchor = format!("{base}-{n}");
                }
                anchors.insert(anchor);
            }
            _ => {}
        }
    }
    Document { links, anchors, broken_references: broken.into_inner() }
}

/// The `href` and `src` values in a piece of raw HTML.
fn html_targets(html: &str) -> Vec<String> {
    let mut targets = Vec::new();
    for attr in ["href=", "src="] {
        let mut rest = html;
        while let Some(at) = rest.find(attr) {
            rest = &rest[at + attr.len()..];
            let Some(quote) = rest.chars().next().filter(|c| *c == '"' || *c == '\'') else { continue };
            let value = &rest[1..];
            if let Some(end) = value.find(quote) {
                targets.push(value[..end].to_string());
            }
        }
    }
    targets
}

/// A heading's anchor, as github-slugger makes it (wyrd.foo and GitHub use it).
fn slug(text: &str) -> String {
    text.to_lowercase()
        .chars()
        .filter(|c| c.is_alphanumeric() || matches!(c, '-' | '_' | ' '))
        .map(|c| if c == ' ' { '-' } else { c })
        .collect()
}

// --- paths ----------------------------------------------------------------------

fn is_url(target: &str) -> bool {
    target
        .split_once(':')
        .is_some_and(|(scheme, _)| !scheme.is_empty() && scheme.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '+' | '-' | '.')))
}

fn split_anchor(target: &str) -> (&str, Option<&str>) {
    let target = target.split('?').next().unwrap();
    match target.split_once('#') {
        Some((path, anchor)) => (path, Some(anchor)),
        None => (target, None),
    }
}

/// `path` with `.` and `..` removed; `None` when it climbs above the root.
fn normalize(path: &Path) -> Option<PathBuf> {
    let mut out = PathBuf::new();
    for part in path.components() {
        match part {
            std::path::Component::CurDir => {}
            std::path::Component::ParentDir => {
                if !out.pop() {
                    return None;
                }
            }
            other => out.push(other),
        }
    }
    Some(out)
}

fn percent_decode(text: &str) -> String {
    let bytes = text.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%'
            && let Some(byte) = text.get(i + 1..i + 3).and_then(|h| u8::from_str_radix(h, 16).ok())
        {
            out.push(byte);
            i += 3;
            continue;
        }
        out.push(bytes[i]);
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}
