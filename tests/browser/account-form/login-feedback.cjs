// Run against the standard container; only admin polling faults are injected.
const { chromium } = require('/runner/node_modules/playwright');
const { default: AxeBuilder } = require('/runner/node_modules/@axe-core/playwright');
const fs = require('node:fs');
const out = '/evidence', origin = 'http://localhost:35317', checks = [];
const result = `${out}/login-feedback-result.json`;
const assert = (ok, message) => { if (!ok) throw Error(message); };
(async () => {
  fs.writeFileSync(result, JSON.stringify({ status: 'failed', reason: 'not completed' }));
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ storageState: `${out}/session.json`, viewport: { width: 1440, height: 1100 }, recordVideo: { dir: out } });
  const page = await context.newPage();
  const mode = async value => { await page.request.get(`http://localhost:35444/fixture/mode?value=${value}`); };
  await mode('normal');
  await page.goto(`${origin}/#/accounts/add`);
  const card = title => page.locator('[data-slot="card"]').filter({ has: page.locator('[data-slot="card-title"]').filter({ hasText: title }) });
  const imports = card('Import a login'), codex = card('Codex (ChatGPT)');
  const imp = async (identity, label) => {
    await page.getByLabel('Label (optional)', { exact: true }).fill(label);
    await page.getByLabel('Credential file', { exact: true }).setInputFiles({ name: 'auth.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ tokens: { access_token: `synthetic-${identity}`, account_id: identity } })) });
    const saved = page.waitForResponse(r => r.url().endsWith('/admin/accounts/import') && r.request().method() === 'POST' && r.status() === 200);
    await imports.getByRole('button', { name: 'Import', exact: true }).click();
    await imports.getByRole('button', { name: 'Importing…' }).waitFor();
    assert(await imports.getByRole('button', { name: 'Importing…' }).isDisabled(), 'Pending import permits duplicate submission');
    const body = await (await saved).json();
    await imports.getByRole('status').filter({ hasText: `Account ID: ${body.id}` }).waitFor();
    assert((await imports.innerText()).includes(label), 'Saved import label missing');
    return body;
  };
  await imp('feedback-failed', 'Discovery failure example');
  await imports.getByRole('alert').filter({ hasText: '503 Service Unavailable' }).waitFor();
  assert((await imports.innerText()).includes('The imported credentials are saved.'), 'Discovery failure hides saved credential');
  await page.screenshot({ path: `${out}/account-import-discovery.png`, fullPage: true });
  await mode('import-models-ok');
  await imports.getByRole('button', { name: 'Refresh models', exact: true }).click();
  await imports.getByRole('listitem').filter({ hasText: 'codex: 1 models' }).waitFor();
  checks.push('Real import saved identity and credentials despite discovery error; Refresh models recovered with one model');
  await imp('feedback-success', 'Discovery success example');
  await imports.getByRole('status').filter({ hasText: 'codex: 1 models found.' }).waitFor();
  await mode('import-models-empty');
  await imp('feedback-empty', 'Empty catalog example');
  await imports.getByRole('status').filter({ hasText: 'codex: 0 models found.' }).waitFor();
  checks.push('Successful and zero-model discovery results rendered from real import responses');
  // Start a real device flow. Inject a status endpoint failure after a successful pending poll.
  await mode('login-pending');
  await codex.getByRole('button', { name: 'Start device login', exact: true }).click();
  await codex.getByRole('status').filter({ hasText: 'Waiting for authorization' }).waitFor();
  const pending = await page.waitForResponse(r => /\/admin\/auth\/flows\/[^/]+$/.test(r.url()) && r.status() === 200);
  assert((await pending.json()).status === 'pending', 'Fixture flow was not pending');
  let polls = 0;
  await page.route('**/admin/auth/flows/*', r => { polls++; return r.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: 'Fixture login status unavailable' } }) }); });
  await codex.getByRole('alert').filter({ hasText: 'Fixture login status unavailable' }).waitFor();
  assert((await codex.innerText()).includes('A successful login has not been confirmed'), 'Polling failure claims success');
  assert(!(await codex.innerText()).includes('Waiting for authorization'), 'Polling failure retains waiting indicator');
  await page.waitForTimeout(6500);
  assert(polls === 1, `Polling/retry continued after HTTP failure: ${polls}`);
  await page.screenshot({ path: `${out}/account-login-polling.png`, fullPage: true });
  for (const scheme of ['light', 'dark']) {
    await page.emulateMedia({ colorScheme: scheme });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(!(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)), 'Phone overflow');
    const axe = await new AxeBuilder({ page }).include('main').analyze();
    assert(axe.violations.length === 0, `Accessibility violations: ${JSON.stringify(axe.violations)}`);
    await page.screenshot({ path: `${out}/account-login-phone-${scheme}.png`, fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 1100 });
  await codex.getByRole('button', { name: 'Start new login', exact: true }).click();
  await page.unroute('**/admin/auth/flows/*');
  await codex.getByRole('button', { name: 'Start device login', exact: true }).waitFor();
  checks.push('HTTP error after pending stops poll/retry, replaces waiting, retains unconfirmed guidance, and offers new login; phone light/dark axe checks passed');
  // Expired flow on the first poll takes the same recovery path.
  await page.route('**/admin/auth/flows/*', r => r.fulfill({ status: 404, contentType: 'application/json', body: JSON.stringify({ error: { message: 'unknown or expired flow' } }) }));
  await codex.getByRole('button', { name: 'Start device login', exact: true }).click();
  await codex.getByRole('alert').filter({ hasText: 'unknown or expired flow' }).waitFor();
  await codex.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.unroute('**/admin/auth/flows/*');
  await mode('login-rejected');
  await codex.getByRole('button', { name: 'Start device login', exact: true }).click();
  await page.getByText(/Codex login failed:.*fixture authorization denied/).waitFor();
  await codex.getByRole('button', { name: 'Start device login', exact: true }).waitFor();
  await mode('login-complete');
  await codex.getByRole('button', { name: 'Start device login', exact: true }).click();
  await page.getByText('Logged in device@example.test', { exact: true }).waitFor();
  await page.getByRole('link', { name: 'Back to accounts' }).click();
  await page.getByRole('button', { name: 'Details for device@example.test' }).waitFor();
  checks.push('First-poll expired flow supports Cancel; real rejected login resets; real successful device login persists account');
  await mode('normal');
  const video = page.video();
  await context.close();
  await video.saveAs(`${out}/account-login-feedback.webm`);
  await browser.close();
  fs.writeFileSync(result, JSON.stringify({ status: 'passed', checks }, null, 2));
  console.log(JSON.stringify({ status: 'passed', checks }, null, 2));
})().catch(error => { fs.writeFileSync(result, JSON.stringify({ status: 'failed', checks, error: String(error) }, null, 2)); console.error(error); process.exit(1); });
